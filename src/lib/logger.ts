export function info(message: string) {
  console.log(`ℹ ${message}`);
}

export function success(message: string) {
  console.log(`✓ ${message}`);
}

export function warning(message: string) {
  console.log(`⚠ ${message}`);
}

export function error(message: string) {
  console.log(`✗ ${message}`);
}
